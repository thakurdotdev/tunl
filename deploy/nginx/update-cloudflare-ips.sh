#!/usr/bin/env bash
# Refresh the Cloudflare IP ranges nginx trusts for tunnel hosts, then reload.
# Run as a user with sudo. Safe to run from cron (e.g. weekly).
set -euo pipefail

dir=/etc/nginx/snippets
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 >"$tmp/v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 >"$tmp/v6"
cat "$tmp/v4" <(echo) "$tmp/v6" | grep -E '^[0-9a-f.:]+/[0-9]+$' >"$tmp/all"

# Refuse to install a suspiciously short list (would lock out real traffic).
if [ "$(wc -l <"$tmp/all")" -lt 10 ]; then
  echo "cloudflare ip list looks wrong, not installing" >&2
  exit 1
fi

{ echo "# generated by update-cloudflare-ips.sh on $(date -u +%F)"; sed 's/.*/set_real_ip_from &;/' "$tmp/all"; echo "real_ip_header CF-Connecting-IP;"; } >"$tmp/realip"
{ echo "# generated by update-cloudflare-ips.sh on $(date -u +%F)"; sed 's/.*/& 1;/' "$tmp/all"; } >"$tmp/geo"

sudo install -m 644 "$tmp/realip" "$dir/tunl-cloudflare-realip.conf"
sudo install -m 644 "$tmp/geo" "$dir/tunl-cloudflare-geo.conf"
sudo nginx -t
sudo systemctl reload nginx
echo "installed $(wc -l <"$tmp/all") cloudflare ranges"
